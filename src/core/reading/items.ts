const FO_LABELS = ["사실", "의견"];
const FO_PRINCIPLE = "사실은 조사하거나 살펴보면 맞는지 알 수 있는 내용이에요. 의견은 사람마다 다를 수 있는 생각이나 느낌이에요.";

function factOpinionLabel(
  id: string, passageId: string, sentenceIds: string[], marks: string, hints: [string, string], explanation: string,
): LabelSentencesItem {
  const answers: Record<string, string> = {};
  sentenceIds.forEach((s, i) => {
    answers[s] = marks[i] === "F" ? "사실" : "의견";
  });
  return {
    id, type: "label-sentences", passageId, standardCode: "4국02-04", grade: 4,
    prompt: "아래 문장은 사실일까요, 의견일까요? 문장마다 알맞은 꼬리표를 골라 보세요.",
    sentenceIds, labels: FO_LABELS, answers,
    principle: FO_PRINCIPLE, hints, explanation,
  };
}

