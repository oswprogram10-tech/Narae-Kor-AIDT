// 읽기 활동 지문(모두 자체 창작). 지문은 평범한 글 문체로 쓰고, 한 편 안에서 문체를 통일한다.
// 문단 id는 p1, p2…, 문장 id는 s{문단}-{순서}(예: s2-3)로 자동으로 붙는다.

import type { Genre, Passage, ReadingItem } from "./types";

/**
 * idPrefix: 두 지문을 한 문제에서 함께 읽는 경우(관점 비교) 문단·문장 id가 겹치지 않도록 붙이는 접두사.
 * 예: "a-" → 문단 "a-p2", 문장 "a-s2-3". 지문 하나만 읽는 문제의 지문에는 쓰지 않는다.
 */
function passage(
  id: string, title: string, genre: Genre, gradeBand: "3-4" | "5-6", paragraphs: string[][], idPrefix = "",
): Passage {
  return {
    id,
    title,
    genre,
    gradeBand,
    paragraphs: paragraphs.map((sentences, pi) => ({
      id: `${idPrefix}p${pi + 1}`,
      sentences: sentences.map((text, si) => ({ id: `${idPrefix}s${pi + 1}-${si + 1}`, text })),
    })),
  };
}

