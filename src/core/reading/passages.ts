// 읽기 활동 지문(모두 자체 창작). 지문은 평범한 글 문체로 쓰고, 한 편 안에서 문체를 통일한다.
// 문단 id는 p1, p2…, 문장 id는 s{문단}-{순서}(예: s2-3)로 자동으로 붙는다.

import type { Genre, Passage } from "./types";

function passage(id: string, title: string, genre: Genre, gradeBand: "3-4" | "5-6", paragraphs: string[][]): Passage {
  return {
    id,
    title,
    genre,
    gradeBand,
    paragraphs: paragraphs.map((sentences, pi) => ({
      id: `p${pi + 1}`,
      sentences: sentences.map((text, si) => ({ id: `s${pi + 1}-${si + 1}`, text })),
    })),
  };
}

