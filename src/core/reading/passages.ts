export function getPassage(id: string): Passage | undefined {
  return READING_PASSAGES.find((p) => p.id === id);
}

/** 지문의 모든 문장을 (문단 id와 함께) 펼쳐 준다. */
export function allSentences(passage: Passage): { paragraphId: string; id: string; text: string }[] {
  return passage.paragraphs.flatMap((p) => p.sentences.map((s) => ({ paragraphId: p.id, id: s.id, text: s.text })));
}
