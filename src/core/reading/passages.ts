/** 다른 학습 모듈(미디어 나래 등)이 읽기 핵심부의 채점·검증이 찾을 수 있게 맡기는 지문 */
const REGISTERED: Passage[] = [];

/** 지문을 읽기 핵심부에 등록한다(같은 id는 한 번만). 읽기 활동 목록(READING_PASSAGES)에는 들어가지 않는다. */
export function registerPassages(list: readonly Passage[]): void {
  for (const p of list) {
    if (READING_PASSAGES.some((x) => x.id === p.id) || REGISTERED.some((x) => x.id === p.id)) continue;
    REGISTERED.push(p);
  }
}

export function getPassage(id: string): Passage | undefined {
  return READING_PASSAGES.find((p) => p.id === id) ?? REGISTERED.find((p) => p.id === id);
}

/** 지문의 모든 문장을 (문단 id와 함께) 펼쳐 준다. */
export function allSentences(passage: Passage): { paragraphId: string; id: string; text: string }[] {
  return passage.paragraphs.flatMap((p) => p.sentences.map((s) => ({ paragraphId: p.id, id: s.id, text: s.text })));
}

/** 문제가 함께 보여 주는 지문들(관점 비교는 둘, 나머지는 하나). 없는 지문은 건너뛴다. */
export function itemPassages(item: Pick<ReadingItem, "passageId" | "passageIds">): Passage[] {
  const ids = item.passageIds ?? [item.passageId];
  return ids.map((id) => getPassage(id)).filter((p): p is Passage => !!p);
}

/**
 * 학생이 이 문제를 풀 때 볼 수 있는 문장(지문 쌍이면 둘 다). revealUpTo가 있으면 그 문단까지만.
 * 근거 문장·고를 수 있는 문장은 이 안에서만 인정한다.
 */
export function visibleSentences(item: Pick<ReadingItem, "passageId" | "passageIds" | "revealUpTo">): { paragraphId: string; id: string; text: string }[] {
  const passages = itemPassages(item);
  return passages.flatMap((p) => {
    let paragraphs = p.paragraphs;
    if (item.revealUpTo !== undefined && p.id === item.passageId) {
      const at = paragraphs.findIndex((x) => x.id === item.revealUpTo);
      if (at >= 0) paragraphs = paragraphs.slice(0, at + 1);
    }
    return allSentences({ ...p, paragraphs });
  });
}
