function res(id: string, title: string, site: string, snippet: string, date?: string, isAd?: boolean): SearchResult {
  return { id, title, site, snippet, ...(date !== undefined ? { date } : {}), ...(isAd ? { isAd: true } : {}) };
}

function searchTask(
  p: Pick<SearchTaskItem, "id" | "grade" | "standardCode" | "purpose" | "queries" | "correctQuery" | "correctResult" | "evidenceIds" | "explanation"> & { hint2: string },
): SearchTaskItem {
  return {
    id: p.id, type: "search-task", standardCode: p.standardCode, grade: p.grade, purpose: p.purpose,
    prompt: "목적에 맞는 검색어를 먼저 고르세요. 그 결과에서 가장 알맞은 것을 고른 뒤, 그렇게 생각한 단서를 눌러 보세요.",
    queries: p.queries, correctQuery: p.correctQuery, correctResult: p.correctResult, evidenceIds: p.evidenceIds,
    principle: SL_PRINCIPLE, hints: [SL_HINT1, p.hint2], explanation: p.explanation,
  };
}

