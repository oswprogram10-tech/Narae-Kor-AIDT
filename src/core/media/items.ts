// ───────── 매체 소통 예절(media-ethics) ─────────
function ethics(
  id: string, passageId: string, grade: 3 | 4, prompt: string, options: string[], correctOption: number,
  evidenceIds: string[] | undefined, principle: string, hints: [string, string], explanation: string,
): ChoiceWithEvidenceItem | ReadingChoiceItem {
  const base = { id, passageId, standardCode: "4국06-03", grade, prompt, options, correctOption, principle, hints, explanation };
  return evidenceIds
    ? { ...base, type: "choice-with-evidence", evidenceIds }
    : { ...base, type: "choice" };
}

