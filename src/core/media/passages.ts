// 미디어 나래 가상 페이지·글(모두 자체 창작). 이름은 모두 지어낸 것이다. 화면에는 늘 "연습용 가상 페이지" 표시를 붙인다.
// 가상 페이지는 첫 문단이 페이지 정보(meta)다: "사이트: …", "주소: …", "글쓴이: …", "날짜: …", "출처: …", "광고: …" 한 줄이 문장 하나.
// id 규칙: 문단 `${접두사}meta`, `${접두사}p1`…, 문장 `${접두사}m-1`…(정보 줄), `${접두사}s1-1`…(본문).

import { registerPassages, type Genre, type PageMeta, type Passage } from "@/core/reading";

interface PageNotes {
  /** page에 값이 없을 때 정보 줄에 적을 말(예: "밝히지 않았어요") */
  author?: string;
  date?: string;
  source?: string;
}

function metaLines(page: PageMeta, notes: PageNotes = {}): string[] {
  const lines = [`사이트: ${page.site}`, `주소: ${page.address}`];
  const author = page.author ?? notes.author;
  const date = page.date ?? notes.date;
  const source = page.sourceNote ?? notes.source;
  if (author !== undefined) lines.push(`글쓴이: ${author}`);
  if (date !== undefined) lines.push(`날짜: ${date}`);
  if (source !== undefined) lines.push(`출처: ${source}`);
  if (page.isAd) lines.push("광고: 이 페이지는 물건을 팔려고 만든 광고예요.");
  return lines;
}

function pagePassage(
  id: string, title: string, genre: Genre, gradeBand: "3-4" | "5-6", prefix: string,
  page: PageMeta, notes: PageNotes, body: string[][],
): Passage {
  return {
    id, title, genre, gradeBand, page,
    paragraphs: [
      {
        id: `${prefix}meta`,
        sentences: metaLines(page, notes).map((text, i) => ({ id: `${prefix}m-${i + 1}`, text })),
      },
      ...body.map((sentences, pi) => ({
        id: `${prefix}p${pi + 1}`,
        sentences: sentences.map((text, si) => ({ id: `${prefix}s${pi + 1}-${si + 1}`, text })),
      })),
    ],
  };
}

function story(id: string, title: string, sentences: string[]): Passage {
  return {
    id, title, genre: "이야기", gradeBand: "3-4",
    paragraphs: [{ id: "p1", sentences: sentences.map((text, si) => ({ id: `s1-${si + 1}`, text })) }],
  };
}

