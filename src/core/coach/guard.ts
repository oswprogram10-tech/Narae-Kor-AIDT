// 비교용 정규화: 띄어쓰기·문장부호·ㅋ/ㅠ 따위를 지운다("죽고시퍼", "맞아서아파요" 같은 아이들의 붙여 쓰기·오타 대응).
function compact(m: string): string {
  return m.toLowerCase().replace(/[\s.,!?~…·ㅠㅜㅋㅎ'"“”‘’]+/g, "");
}

interface Rule {
  re: RegExp;
  // 이 글이 함께 있으면 해당 규칙만 적용하지 않는다(규칙별 예외).
  unless?: RegExp;
}
const ruleHit = (rules: Rule[], s: string): boolean => rules.some((r) => r.re.test(s) && !(r.unless && r.unless.test(s)));

