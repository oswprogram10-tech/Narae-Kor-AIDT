// 문학 나래 작품(모두 자체 창작). 동화는 문단이, 시는 연이 문단이고 시의 한 행이 문장 하나다.
// id 규칙은 읽기와 같다: 문단 p1, p2…, 문장 s{문단}-{순서}.

import { registerPassages, type Genre, type Passage } from "@/core/reading";

function work(id: string, title: string, genre: Genre, gradeBand: "3-4" | "5-6", paragraphs: string[][]): Passage {
  return {
    id, title, genre, gradeBand,
    paragraphs: paragraphs.map((sentences, pi) => ({
      id: `p${pi + 1}`,
      sentences: sentences.map((text, si) => ({ id: `s${pi + 1}-${si + 1}`, text })),
    })),
  };
}

