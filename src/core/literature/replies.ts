const BY_ID = new Map(REPLY_CHARACTERS.map((c) => [c.id, c]));

export function getReplyCharacter(id: string): ReplyCharacter | undefined {
  return BY_ID.get(id);
}

// 같은 작품에 나오지만 답장 인물로 쓰지 않는 이름(문장 조각에 이름만 나올 수 있다).
export const EXTRA_WORK_NAMES: Record<string, readonly string[]> = { "lt-kite": ["달수"] };

// '받는 인물' 칸의 글에서 답장할 인물을 짐작한다. 작품 이름(「…」, 작품 제목)은 지우고 가장 먼저 나온 이름을 고른다.
export function guessReplyCharacter(receiverText: string): string | null {
  let text = receiverText.replace(/[「『][^」』]*[」』]/g, " ");
  for (const c of REPLY_CHARACTERS) text = text.split(c.workTitle).join(" ");
  let best: { id: string; at: number } | null = null;
  for (const c of REPLY_CHARACTERS) {
    for (const key of [c.name, ...c.aliases]) {
      const at = text.indexOf(key);
      if (at >= 0 && (!best || at < best.at)) best = { id: c.id, at };
    }
  }
  return best?.id ?? null;
}
