// 듣기 자료(모두 자체 창작): 발표·대화·연설. 말차례 하나가 문단 하나이고, 문단마다 말한 사람(speaker)이 있다.
// id 규칙은 읽기와 같다: 문단 p1, p2…, 문장 s{문단}-{순서}. 지문 id는 "ls-"로 시작한다.
// 이름은 지어낸 이름(성 없이)만 쓴다. 학생에게는 처음에 글을 숨기고 소리로 들려준다.

import { registerPassages, type Genre, type Passage } from "@/core/reading";

/** turns: [말한 사람, 그 말차례의 문장들][] */
function talk(
  id: string, title: string, genre: Genre, gradeBand: "3-4" | "5-6", turns: [string, string[]][],
): Passage {
  return {
    id, title, genre, gradeBand,
    paragraphs: turns.map(([speaker, sentences], pi) => ({
      id: `p${pi + 1}`,
      speaker,
      sentences: sentences.map((text, si) => ({ id: `s${pi + 1}-${si + 1}`, text })),
    })),
  };
}

