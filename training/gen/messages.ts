function generatePersonal(seed: number, pool: PersonalPool, perType: number): string[] {
  const rand = makeRand(seed);
  const pick = <T>(xs: T[]): T => xs[Math.floor(rand() * xs.length)];
  const digits = (n: number) => Array.from({ length: n }, () => Math.floor(rand() * 10)).join("");
  const phone = () => pick(pool.phoneFormats)(`0${digits(3)}`, digits(4));
  const name = () => pick(pool.surnames) + pick(pool.givens);
  const addr = () => {
    const n = 1 + Math.floor(rand() * 98);
    const m = 1 + Math.floor(rand() * 40);
    switch (Math.floor(rand() * 4)) {
      case 0: return `${pick(pool.towns)}동 ${n}-${m}`;
      case 1: return `${pick(pool.roads)}로 ${n}번길 ${m}`;
      case 2: return `${pick(pool.complexes)} ${100 + Math.floor(rand() * 20)}동 ${100 * (1 + Math.floor(rand() * 20)) + Math.floor(rand() * 4) + 1}호`;
      default: return `${pick(pool.towns)}길 ${n} ${pick(pool.complexes)} ${m}호`;
    }
  };
  const vars = (): Record<string, string> => ({
    phone: phone(),
    addr: addr(),
    school: pick(pool.schools),
    grade: String(3 + Math.floor(rand() * 4)),
    cls: String(1 + Math.floor(rand() * 9)),
    name: name(),
    mom: name(),
    dad: name(),
    email: `${pick(pool.mailUsers)}${digits(2 + Math.floor(rand() * 3))}@example.com`,
    id: `${pick(pool.idWords)}${rand() < 0.5 ? "_" : ""}${digits(2 + Math.floor(rand() * 3))}`,
    y: String(pool.yearRange[0] + Math.floor(rand() * (pool.yearRange[1] - pool.yearRange[0] + 1))),
    m: String(1 + Math.floor(rand() * 12)),
    d: String(1 + Math.floor(rand() * 28)),
  });
  const kinds = Object.keys(pool.templates) as (keyof PersonalPool["templates"])[];
  const out: string[] = [];
  const seen = new Set<string>();
  for (const kind of kinds) {
    let made = 0;
    let guard = 0;
    while (made < perType && guard++ < perType * 50) {
      const t = pool.templates[kind];
      const text = t[made % t.length](vars());
      if (seen.has(text)) continue;
      seen.add(text);
      out.push(text);
      made++;
    }
  }
  return out;
}

